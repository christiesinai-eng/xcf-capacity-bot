#!/usr/bin/env node
'use strict';
// Writes brand/mockup.scoped.css from brand/source/mockup.css (the CSS of the "XCF Lighthouse - dashboard mockup" page).
//
//   node scripts/scope-mockup-css.js
//
// Every rule is prefixed with `.mk ` so the mockup's class names (.card, .chip, .bar, .dot ...) apply only inside the new
// overview page and can never touch the report's own tabs. Rules for the page frame (sidebar, header, theme button, the
// mockup's own dialog) are left out: brand/brand.css owns those. Colour tokens are renamed to the report's:
// --surface (the mockup's card white) becomes --card, the two font variables become --head and --body.

const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'brand', 'source', 'mockup.css');
const OUT = path.join(ROOT, 'brand', 'mockup.scoped.css');

const SKIP = /^(:root|html|\*|body|h1|ul|button|a$|a\b[^-]|:focus-visible|\.app\b|\.nav\b|\.brand\b|\.navgrp\b|main\b|\.theme\b|\.top\b|\.upd-meta|\.accent|dialog|\.dhead|\.dclose|#dBody|\.foot\b)/;
// the mockup's "See more" window content (tables, bars, notes): scoped to the window instead of the page
const DIALOG = /^(\.dsec|\.tscroll|\.dt\b|\.dgrid|\.hb\b|\.note2)/;

function strip(css) { return css.replace(/\/\*[\s\S]*?\*\//g, ''); }
function parse(css, i, end) {
  const nodes = [];
  while (i < end) {
    while (i < end && /\s/.test(css[i])) i++;
    if (i >= end) break;
    const open = css.indexOf('{', i);
    if (open < 0 || open >= end) break;
    const head = css.slice(i, open).trim();
    let depth = 1, j = open + 1;
    while (j < end && depth) { if (css[j] === '{') depth++; else if (css[j] === '}') depth--; j++; }
    const body = css.slice(open + 1, j - 1);
    if (head.startsWith('@media')) nodes.push({ at: head, children: parse(body, 0, body.length) });
    else if (!head.startsWith('@')) nodes.push({ selector: head, body: body.trim() });
    i = j;
  }
  return nodes;
}
function emit(nodes) {
  let out = '';
  for (const n of nodes) {
    if (n.children) { const inner = emit(n.children); if (inner.trim()) out += `${n.at}{\n${inner}}\n`; continue; }
    const parts = n.selector.split(',').map((s) => s.trim()).filter((s) => s && !SKIP.test(s));
    if (!parts.length) continue;
    out += `${parts.map((s) => (DIALOG.test(s) ? `#ct-detail ${s}` : `.mk ${s}`)).join(',')}{${n.body}}\n`;
  }
  return out;
}

let css = strip(fs.readFileSync(SRC, 'utf8'));
css = css.replace(/var\(--surface\)/g, 'var(--card)').replace(/var\(--font-head\)/g, 'var(--head)').replace(/var\(--font-body\)/g, 'var(--body)');
const out = '/* GENERATED by scripts/scope-mockup-css.js from brand/source/mockup.css. Do not edit by hand. */\n' + emit(parse(css, 0, css.length));
fs.writeFileSync(OUT, out, 'utf8');
console.log(`Wrote ${path.relative(ROOT, OUT)} (${out.split('\n').length} lines, ${(out.length / 1024).toFixed(1)} KB)`);
